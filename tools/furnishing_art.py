def _rgba(value):
    return tuple((value >> shift) & 255 for shift in (16, 8, 0)) + (255,)


def detail(image, strokes, colors):
    """Clip authored material strokes to existing opaque surfaces."""
    layer = Image.new("RGBA", image.size)
    draw = ImageDraw.Draw(layer)
    for role, points in strokes:
        draw.line(points, fill=colors[role])
    mask = image.getchannel("A")
    layer.putalpha(Image.composite(layer.getchannel("A"), Image.new("L", image.size), mask))
    image.alpha_composite(layer)
    return image


def catalogue(image, name, kind, source_ramps, target_ramps, ink):
    """Shade each connected material plane, then add its named construction details."""
    palette = [ink] + [_rgba(value) for ramp in target_ramps for value in ramp]
    structure = [_rgba(value) for value in target_ramps[0]]
    half_light = tuple((structure[1][i] + structure[2][i]) // 2 for i in range(3)) + (255,)
    half_shadow = tuple((structure[0][i] + structure[1][i]) // 2 for i in range(3)) + (255,)
    original = image.copy()
    # Disconnected objects get their own light planes, not one global diagonal.
    for old_ramp, new_ramp in zip(source_ramps, target_ramps):
        body = _rgba(old_ramp[1])
        remaining = {(x, y) for y in range(image.height) for x in range(image.width)
                     if original.getpixel((x, y)) == body}
        while remaining:
            seed = remaining.pop()
            cluster, pending = {seed}, [seed]
            while pending:
                x, y = pending.pop()
                for point in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
                    if point in remaining:
                        remaining.remove(point)
                        cluster.add(point)
                        pending.append(point)
            x0, y0 = min(x for x, _ in cluster), min(y for _, y in cluster)
            x1, y1 = max(x for x, _ in cluster), max(y for _, y in cluster)
            span = max(1, x1 - x0 + y1 - y0)
            for x, y in cluster:
                position = (x - x0 + y - y0) * 10
                tone = 2 if position < span * 3 else 0 if position > span * 7 else 1
                color = _rgba(new_ramp[tone])
                if old_ramp == source_ramps[0]:
                    if span * 3 <= position < span * 4:
                        color = half_light
                    elif span * 6 < position <= span * 7:
                        color = half_shadow
                image.putpixel((x, y), color)
    recipes = DECOR_DETAILS if kind == "decor" else GIFT_DETAILS if kind == "gift" else TREAT_DETAILS
    detail(image, recipes[name], palette)
    if kind == "decor":
        _themed_anatomy(image, name, palette)
    return image


def existing(image, name, kind):
    """Keep the original natural-prop/gift materials with new authored surfaces."""
    image = image.resize((image.width // 2, image.height // 2), Image.Resampling.NEAREST)
    colors = sorted({pixel for pixel in image.get_flattened_data() if pixel[3]},
                    key=lambda p: p[0] * 299 + p[1] * 587 + p[2] * 114)
    # Select existing ramp tones; never quantize, invent gradients or grow palettes.
    roles = [colors[0]] + [colors[round((len(colors) - 1) * fraction)]
                          for fraction in (.18, .45, .85, .25, .6, 1, .2, .5, .9)]
    recipes = DECOR_DETAILS if kind == "decor" else GIFT_DETAILS
    detail(image, recipes[name], roles)
    if kind == "decor":
        _natural_inserts(image, name)
    return image.resize((image.width * 2, image.height * 2), Image.Resampling.NEAREST)


def _natural_inserts(image, name):
    """Reuse the approved natural material anatomy where objects share it."""
    inserts = {
        "fern_pot": (("fern", (7, 0, 25, 20)),),
        "mushroom_pair": (("mushroom", (1, 4, 19, 27)), ("mushroom", (17, 13, 30, 29))),
        "flower_planter": (("flower_pink", (5, 5, 15, 18)), ("flower_white", (13, 2, 23, 16)),
                           ("flower_pink", (21, 7, 30, 19))),
        "moss_stone": (("rock_large", (2, 10, 30, 29)), ("moss_clump", (4, 8, 28, 23))),
        "crystal_cluster": (("crystal", (1, 1, 31, 30)),),
    }
    if name not in inserts:
        return
    # The approved sources have different palettes; reduce to the existing finite
    # material ramps explicitly, so a composite cannot exceed the 12-tone budget.
    colors = sorted({pixel for pixel in image.get_flattened_data() if pixel[3]})
    draw = ImageDraw.Draw(image)
    if name in ("mushroom_pair", "crystal_cluster"):
        draw.rectangle((0, 0, 31, 31), fill=(0, 0, 0, 0))
    elif name == "flower_planter":
        def material(rgb):
            return min(colors, key=lambda color: sum((color[i] - rgb[i]) ** 2 for i in range(3)))
        draw.rectangle((0, 0, 31, 31), fill=(0, 0, 0, 0))
        draw.polygon([(4, 19), (28, 19), (25, 28), (7, 28)], fill=material((22, 24, 35)))
        draw.polygon([(6, 20), (26, 20), (23, 26), (9, 26)], fill=material((174, 116, 61)))
        draw.line([(7, 20), (25, 20)], fill=material((234, 197, 138)))
        for x in (11, 18, 23):
            draw.line([(x, 22), (x - 1, 25)], fill=material((98, 60, 57)))
        for x, y in ((10, 15), (18, 13), (25, 16)):
            draw.line([(x, y), (x, 20)], fill=material((36, 91, 73)))
            draw.line([(x, 18), (x - 2, 16)], fill=material((82, 150, 58)))
    for source, box in inserts[name]:
        prop = core_decor_art.draw(source).resize((32, 32), Image.Resampling.NEAREST)
        prop = prop.crop(prop.getbbox()).resize((box[2] - box[0], box[3] - box[1]),
                                               Image.Resampling.NEAREST)
        if name in ("mushroom_pair", "crystal_cluster"):
            image.alpha_composite(prop, box[:2])
            continue
        mapped = {}
        for color in {pixel for pixel in prop.get_flattened_data() if pixel[3]}:
            mapped[color] = min(colors, key=lambda target: sum(
                (color[i] - target[i]) ** 2 for i in range(3)))
        prop.putdata([mapped.get(pixel, pixel) for pixel in prop.get_flattened_data()])
        image.alpha_composite(prop, box[:2])


