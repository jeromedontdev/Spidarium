"""Generate main/climb_mask.h from the installed climb-structure artwork.

The large climb structures are diagonal logs, branches and arches, not squares.
A circular footprint centred on the sprite therefore covers a lot of empty
corner: the spider was reported as "well above the decor item" while still
counting as standing on it, with the contact shadow far away.

A per-row span table fixes that exactly. For each source row it records the
first and last opaque column, so the hit test asks "is this point on the
artwork" instead of "is this point inside a circle". Rows with small gaps
(between two branches of a vine, say) are recorded as one span: a spider
standing in a gap between branches is still on the structure.

The table is in SOURCE pixels (96x96). The sprite is drawn at LVGL scale 512,
which is 2x, and LVGL scales about the image centre, so a screen point maps to
source with

    sx = (x - item->x) / 2 + DECOR_CLIMB_SPRITE / 2
    sy = (y - item->y) / 2 + DECOR_CLIMB_SPRITE / 2

Usage:
    python tools/climb_mask.py            # rewrite main/climb_mask.h
    python tools/climb_mask.py --check    # fail if the header is stale
"""

import argparse
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
HEADER = ROOT / "main" / "climb_mask.h"
JS_MODULE = ROOT / "site" / "lib" / "climb-mask.js"

# Must match the order of the large climb structures in main/decor.c.
NAMES = ["branch", "vine", "root", "ivy", "boulder", "driftwood"]

# Alpha at or below this counts as transparent. The importer restores binary
# alpha, so anything above zero is real artwork.
ALPHA_MIN = 8


def spans(path):
    """Per-row (first, last) opaque column, or None for an empty row."""
    image = Image.open(path).convert("RGBA")
    width, height = image.size
    alpha = image.split()[3].load()
    rows = []
    for y in range(height):
        xs = [x for x in range(width) if alpha[x, y] > ALPHA_MIN]
        rows.append((min(xs), max(xs)) if xs else None)
    return width, height, rows


def build():
    out = []
    for name in NAMES:
        path = ASSETS / f"decoritem_climb_{name}.png"
        if not path.exists():
            raise SystemExit(f"missing artwork: {path}")
        width, height, rows = spans(path)
        if width != 96 or height != 96:
            raise SystemExit(f"{path.name} is {width}x{height}, expected 96x96")
        out.append((name, rows))
    return out


def render(tables):
    lines = [
        "/* Generated by tools/climb_mask.py -- do not edit by hand.",
        " *",
        " * Per-row opaque span of each large climb structure, in SOURCE pixels.",
        " * The sprites are diagonal logs and arches, so a circular footprint",
        " * covered the empty corners and the spider counted as standing on the",
        " * item while visibly above it. A span table asks the real question: is",
        " * this point on the artwork?",
        " *",
        " * Regenerate after changing the climb art:",
        " *     python tools/climb_mask.py",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#include \"decor.h\"",
        "",
        "typedef struct {",
        "    uint8_t first;  /* first opaque source column, inclusive */",
        "    uint8_t last;   /* last opaque source column, inclusive */",
        "    uint8_t empty;  /* 1 when the row has no artwork at all */",
        "} climb_span_t;",
        "",
        f"#define CLIMB_MASK_ROWS {len(tables[0][1])}",
        f"#define CLIMB_MASK_COUNT {len(tables)}",
        "",
        "static const climb_span_t k_climb_mask[CLIMB_MASK_COUNT][CLIMB_MASK_ROWS] = {",
    ]
    for name, rows in tables:
        lines.append(f"    /* {name} */ {{")
        for y, span in enumerate(rows):
            if span is None:
                lines.append("        {0, 0, 1},")
            else:
                lines.append(f"        {{{span[0]}, {span[1]}, 0}},")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def render_js(tables):
    """The same table for the browser engine, so both sides agree exactly."""
    lines = [
        "// Generated by tools/climb_mask.py -- do not edit by hand.",
        "//",
        "// Per-row opaque span of each large climb structure, in SOURCE pixels.",
        "// The sprites are diagonal logs and arches, so a circular footprint",
        "// covered the empty corners and the spider counted as standing on the",
        "// item while visibly above it. Mirrors main/climb_mask.h.",
        "//",
        "// Regenerate after changing the climb art:",
        "//     python tools/climb_mask.py",
        "",
        "// [first, last] per source row, or null for an empty row.",
        "export const CLIMB_MASK = [",
    ]
    for name, rows in tables:
        lines.append(f"  // {name}")
        lines.append("  [")
        for span in rows:
            lines.append("    null," if span is None else f"    [{span[0]},{span[1]}],")
        lines.append("  ],")
    lines.append("];")
    lines.append("")
    lines.append("export const CLIMB_MASK_ROWS = 96;")
    lines.append("export const CLIMB_MASK_COUNT = %d;" % len(tables))
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if the generated files do not match the artwork")
    args = parser.parse_args()

    tables = build()
    text = render(tables)
    js = render_js(tables)
    if args.check:
        stale = []
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
            stale.append(str(HEADER.relative_to(ROOT)))
        if not JS_MODULE.exists() or JS_MODULE.read_text(encoding="utf-8") != js:
            stale.append(str(JS_MODULE.relative_to(ROOT)))
        if stale:
            print("stale: " + ", ".join(stale) +
                  "; run python tools/climb_mask.py", file=sys.stderr)
            return 1
        print("climb mask matches the artwork")
        return 0

    HEADER.write_text(text, encoding="utf-8", newline="\n")
    JS_MODULE.write_text(js, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER.relative_to(ROOT)} and {JS_MODULE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
